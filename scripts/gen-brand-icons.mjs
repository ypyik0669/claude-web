// Generates web/src/ui/brand-icons.generated.ts: the marks of the services in the connector directory, taken from
// simple-icons (CC0-1.0).
//
//   node scripts/gen-brand-icons.mjs
//
// Input:  web/src/ui/brand-map.json   connector id → simple-icons slug ("$comment" ignored)
//         node_modules/simple-icons    (a dev dependency of web: the app never imports it at runtime)
// Output: `BRAND_ICONS`, connector id → { path, hex } — one 24 × 24 path and the brand's colour.
//
// A slug simple-icons does not carry (it drops marks whose owners ask) is skipped with a warning: that connector is
// drawn with one of the app's own icons instead (web/src/features/extensions/brands.ts).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MAP_FILE = path.join(ROOT, 'web', 'src', 'ui', 'brand-map.json');
const OUT_FILE = path.join(ROOT, 'web', 'src', 'ui', 'brand-icons.generated.ts');

const require = createRequire(path.join(ROOT, 'web', 'package.json'));
const icons = require('simple-icons');
// (the package does not export its package.json: read it from the folder its entry is in)
const version = (() => {
  for (let dir = path.dirname(require.resolve('simple-icons')); path.dirname(dir) !== dir; dir = path.dirname(dir)) {
    try { const p = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')); if (p.name === 'simple-icons') return p.version; } catch { /* keep walking up */ }
  }
  return 'unknown';
})();

const map = JSON.parse(readFileSync(MAP_FILE, 'utf8'));
const key = (slug) => `si${slug[0].toUpperCase()}${slug.slice(1)}`;
const rows = [];
const missing = [];
for (const [id, slug] of Object.entries(map)) {
  if (id.startsWith('$')) continue;
  const icon = icons[key(slug)];
  if (!icon || typeof icon.path !== 'string' || !/^[0-9A-Fa-f]{6}$/.test(icon.hex)) { missing.push(`${id} → ${slug}`); continue; }
  rows.push(`  ${JSON.stringify(id)}: { path: ${JSON.stringify(icon.path)}, hex: ${JSON.stringify(icon.hex.toLowerCase())} },`);
}

const out = `// Generated by scripts/gen-brand-icons.mjs from simple-icons@${version} (CC0-1.0) — do not edit.
// The marks belong to their owners; they are here only to name the service a connector talks to.
export const BRAND_ICONS: Record<string, { path: string; hex: string }> = {
${rows.join('\n')}
};
`;
writeFileSync(OUT_FILE, out);
console.log(`${path.relative(ROOT, OUT_FILE)}: ${rows.length} marks from simple-icons@${version}`);
if (missing.length) console.warn(`not in simple-icons (drawn with our own icon): ${missing.join(', ')}`);
